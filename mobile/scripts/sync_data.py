#!/usr/bin/env python3
"""Copy the question bank, notes and curriculum from ../web into bundled app data.

Writes data/questions.json, data/notes.json, data/curriculum.json, copies images into
assets/q and assets/notes, and generates data/images.ts (path -> require()) so Metro bundles them.
Re-run after `python3 web/build.py`.
"""
import json, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(os.path.dirname(ROOT), 'web')

def load_js(name):
    src = open(os.path.join(WEB, 'data', name), encoding='utf-8').read()
    return json.loads(src[src.index('=') + 1:].strip().rstrip(';'))

questions, notes, curriculum = load_js('questions.js'), load_js('notes.js'), load_js('curriculum.js')
images = {}

def local(path, folder):
    """Copy a web-relative image into assets/<folder> and return its key (or the original URL)."""
    if path.startswith('http'):
        return path
    src = os.path.join(WEB, path.replace('%20', ' '))
    name = re.sub(r'[^A-Za-z0-9._-]', '_', os.path.basename(src))
    dst = os.path.join(ROOT, 'assets', folder, name)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if not os.path.exists(dst):
        shutil.copyfile(src, dst)
    key = f'{folder}/{name}'
    images[key] = f'../assets/{key}'
    return key

for q in questions:
    q['qimg'] = [local(p, 'q') for p in q['qimg']]
    q['aimg'] = [local(p, 'q') for p in q['aimg']]
for n in notes:
    n['md'] = re.sub(r'!\[([^\]]*)\]\((notes/img/[^)]+)\)', lambda m: f'![{m.group(1)}]({local(m.group(2), "notes")})', n['md'])

for name, data in (('questions', questions), ('notes', notes), ('curriculum', curriculum)):
    json.dump(data, open(os.path.join(ROOT, 'data', f'{name}.json'), 'w'), ensure_ascii=False)
with open(os.path.join(ROOT, 'data', 'images.ts'), 'w') as f:
    f.write('// Generated by scripts/sync_data.py — do not edit.\n')
    f.write('export const IMAGES: Record<string, number> = {\n')
    for k, v in sorted(images.items()):
        f.write(f'  {json.dumps(k)}: require({json.dumps(v)}),\n')
    f.write('};\n')
print(f'{len(questions)} questions, {len(notes)} notes, {len(curriculum)} units, {len(images)} images')
